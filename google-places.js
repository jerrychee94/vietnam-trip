window.googlePlaceMeta = function (name) {
  return window.GOOGLE_PLACES[name] || null;
};

window.googleMapsUrl = function (name) {
  const meta = window.googlePlaceMeta(name);
  const query = encodeURIComponent(meta?.query || name);
  return `https://www.google.com/maps/search/?api=1&query=${query}`;
};

window.googleReviewsUrl = function (name) {
  const meta = window.googlePlaceMeta(name);
  const query = encodeURIComponent((meta?.query || name) + " reviews");
  return `https://www.google.com/maps/search/${query}`;
};

window.googleImagesUrl = function (name) {
  const meta = window.googlePlaceMeta(name);
  const query = encodeURIComponent(meta?.query || name);
  return `https://www.google.com/search?tbm=isch&q=${query}`;
};

window.formatReviewCount = function (count) {
  if (count >= 1000) {
    const k = count / 1000;
    return `${k >= 10 ? Math.round(k) : k.toFixed(1).replace(/\.0$/, "")}k`;
  }
  return String(count);
};

window.renderGoogleRating = function (name) {
  const meta = window.googlePlaceMeta(name);
  if (!meta?.rating) return "";

  const fullStars = Math.floor(meta.rating);
  const half = meta.rating - fullStars >= 0.25 && meta.rating - fullStars < 0.75;
  const stars =
    "★".repeat(fullStars) +
    (half ? "½" : meta.rating - fullStars >= 0.75 ? "★" : "") +
    "☆".repeat(5 - fullStars - (half || meta.rating - fullStars >= 0.75 ? 1 : 0));

  return `
    <a class="google-rating" href="${window.googleReviewsUrl(name)}" target="_blank" rel="noopener" aria-label="${meta.rating} stars, ${meta.reviews} Google reviews for ${name}">
      <span class="google-mark" aria-hidden="true">G</span>
      <span class="google-stars" aria-hidden="true">${stars.slice(0, 5)}</span>
      <strong>${meta.rating.toFixed(1)}</strong>
      <span class="google-reviews">(${window.formatReviewCount(meta.reviews)} reviews)</span>
    </a>
  `;
};
